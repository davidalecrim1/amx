type Options struct {
	DryRun bool
	Home   string
	Out    io.Writer
}

var claudeEvents = []string{
	"SessionStart",
	"UserPromptSubmit",
	"PreToolUse",
	"PostToolUse",
	"PostToolUseFailure",
	"PermissionRequest",
	"PermissionDenied",
	"Notification",
	"Stop",
	"StopFailure",
	"SessionEnd",
}

func Run(opts Options) error {
	if opts.Out == nil {
		opts.Out = os.Stdout
	}
	home := opts.Home
	if home == "" {
		h, err := os.UserHomeDir()
		if err != nil {
			return err
		}
		home = h
	}
	opts.Home = home
	exe, err := os.Executable()
	if err != nil {
		return err
	}
	if resolved, err := filepath.EvalSymlinks(exe); err == nil {
		exe = resolved
	}

	snippet := filepath.Join(home, ".config", "amx", "tmux.conf")
	tmuxConf := mainTmuxConf(home)
	claudeSettings := filepath.Join(home, ".claude", "settings.json")
	plugin := filepath.Join(home, ".config", "opencode", "plugins", "amx.js")

	fmt.Fprintf(opts.Out, "binary: %s\n\n", exe)
	if !opts.DryRun {
		migrateState(home)
	}

	if err := writeSnippet(snippet, exe, tmuxSupportsTerminalColour(), opts); err != nil {
		return err
	}
	if err := ensureSource(tmuxConf, snippet, opts); err != nil {
		return err
	}
	if err := installLiveHooks(exe, opts); err != nil {
		fmt.Fprintf(opts.Out, "tmux hooks: could not apply live (%v); they will load on next config source\n", err)
	}
	if err := mergeClaude(claudeSettings, exe, opts); err != nil {
		return err
	}
	if err := writePlugin(plugin, exe, opts); err != nil {
		return err
	}
	cleanupLegacy(home, opts)

	fmt.Fprintln(opts.Out, "")
	if opts.DryRun {
		fmt.Fprintln(opts.Out, "dry run: nothing written")
		return nil
	}
	fmt.Fprintln(opts.Out, "next:")
	fmt.Fprintln(opts.Out, "  tmux source-file ~/.config/amx/tmux.conf   (or reload your tmux config)")
	fmt.Fprintln(opts.Out, "  restart Claude Code so the new hooks load")
	fmt.Fprintln(opts.Out, "  restart OpenCode so the plugin loads")
	return nil
}

func migrateState(home string) {
	root := filepath.Join(home, ".local", "state", "amx")
	if h, err := os.UserHomeDir(); err == nil && filepath.Clean(home) == filepath.Clean(h) {
		root = state.DefaultRoot()
	}
	oldRoot := filepath.Join(filepath.Dir(root), "amux")
	if _, err := os.Stat(oldRoot); err != nil {
		return
	}
	if _, err := os.Stat(root); err == nil {
		return
	}
	_ = os.Rename(oldRoot, root)
}

func cleanupLegacy(home string, opts Options) {
	oldPlugin := filepath.Join(home, ".config", "opencode", "plugins", "amux.js")
	if data, err := os.ReadFile(oldPlugin); err == nil && strings.HasPrefix(string(data), "// amux: generated by amux setup") {
		if opts.DryRun {
			fmt.Fprintf(opts.Out, "opencode plugin: would remove old %s\n", oldPlugin)
		} else if err := os.Remove(oldPlugin); err == nil {
			fmt.Fprintf(opts.Out, "opencode plugin: removed old %s\n", oldPlugin)
		}
	}
	oldConf := filepath.Join(home, ".config", "amux", "tmux.conf")
	if data, err := os.ReadFile(oldConf); err == nil && strings.HasPrefix(string(data), "# Generated by amux setup") {
		if opts.DryRun {
			fmt.Fprintf(opts.Out, "tmux snippet: would remove old %s\n", filepath.Dir(oldConf))
		} else if err := os.RemoveAll(filepath.Dir(oldConf)); err == nil {
			fmt.Fprintf(opts.Out, "tmux snippet: removed old %s\n", filepath.Dir(oldConf))
		}
	}
}

func mainTmuxConf(home string) string {
	candidates := []string{
		filepath.Join(home, ".config", "tmux", "tmux.conf"),
		filepath.Join(home, ".tmux.conf"),
	}
	for _, c := range candidates {
		if _, err := os.Stat(c); err == nil {
			return c
		}
	}
	return candidates[0]
}

func snippetContent(exe string, terminalBG bool) string {
	style := ""
	prefix := ""
	if terminalBG {
		style = " -s 'bg=terminal'"
	} else {
		// Before 3.8 there is no bg=terminal. Clear the theme's popup-style
		// right before opening so tmux's default style (the terminal
		// background) applies.
		prefix = `set-option -gu popup-style \; `
	}
	return fmt.Sprintf(`# Generated by amx setup. Edit amx, not this file.
bind W %sdisplay-popup -E -w 90%% -h 85%% -T ' Agent Multiplexer ' -b rounded -S 'fg=brightblack'%s '%s pick'
bind u run-shell -b "%s unread #{pane_id}"
set-hook -g after-select-pane 'run-shell -b "%s focus #{pane_id}"'
set-hook -g after-select-window 'run-shell -b "%s focus #{session_name}:#{window_index}"'
set-hook -g client-session-changed 'run-shell -b "%s focus #{session_name}:#{window_index}"'
`, prefix, style, exe, exe, exe, exe, exe)
}

var tmuxVersionRE = regexp.MustCompile(`(\d+)\.(\d+)`)

// tmuxSupportsTerminalColour reports whether bg=terminal is available. It was
// added with the theme colour work in tmux 3.8; older versions reject it.
func tmuxSupportsTerminalColour() bool {
	out, err := exec.Command("tmux", "-V").Output()
	if err != nil {
		return false
	}
	m := tmuxVersionRE.FindStringSubmatch(string(out))
	if len(m) != 3 {
		return false
	}
	major, _ := strconv.Atoi(m[1])
	minor, _ := strconv.Atoi(m[2])
	return major > 3 || (major == 3 && minor >= 8)
}

func writeSnippet(path, exe string, terminalBG bool, opts Options) error {
	want := snippetContent(exe, terminalBG)
	have, err := os.ReadFile(path)
	if err == nil && string(have) == want {
		fmt.Fprintf(opts.Out, "tmux snippet: unchanged (%s)\n", path)
		return nil
	}
	if opts.DryRun {
		fmt.Fprintf(opts.Out, "tmux snippet: would write %s\n", path)
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(opts.Out, "tmux snippet: wrote %s\n", path)
	return nil
}

func ensureSource(mainConf, snippet string, opts Options) error {
	line := "source-file " + strings.Replace(snippet, opts.Home, "~", 1)
	data, err := os.ReadFile(mainConf)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	body := string(data)
	if strings.Contains(body, "amux/tmux.conf") {
		lines := strings.Split(body, "\n")
		out := make([]string, 0, len(lines))
		replaced := false
		for _, l := range lines {
			if strings.Contains(l, "source") && strings.Contains(l, "amux/tmux.conf") {
				if !replaced {
					out = append(out, strings.Replace(l, "amux/tmux.conf", "amx/tmux.conf", 1))
					replaced = true
				}
				continue
			}
			out = append(out, l)
		}
		body = strings.Join(out, "\n")
		if replaced {
			if opts.DryRun {
				fmt.Fprintf(opts.Out, "tmux config: would migrate source line in %s\n", mainConf)
			} else {
				if err := os.WriteFile(mainConf, []byte(body), 0o644); err != nil {
					return err
				}
				fmt.Fprintf(opts.Out, "tmux config: migrated source line in %s\n", mainConf)
			}
			data = []byte(body)
		}
	}
	if strings.Contains(string(data), "amx/tmux.conf") {
		fmt.Fprintf(opts.Out, "tmux config: already sources amx (%s)\n", mainConf)
		return nil
	}
	body = string(data)
	if body != "" && !strings.HasSuffix(body, "\n") {
		body += "\n"
	}
	body += "\n# amx\n" + line + "\n"
	if opts.DryRun {
		fmt.Fprintf(opts.Out, "tmux config: would append %q to %s\n", line, mainConf)
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(mainConf), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(mainConf, []byte(body), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(opts.Out, "tmux config: appended source line to %s\n", mainConf)
	return nil
}

func installLiveHooks(exe string, opts Options) error {
	if opts.DryRun {
		fmt.Fprintln(opts.Out, "tmux hooks: would install after-select-pane, after-select-window, client-session-changed")
		return nil
	}
	hooks := []string{"after-select-pane", "after-select-window", "client-session-changed"}
	for _, h := range hooks {
		_ = tmux.UnsetHooks(h, "amux focus") // old name
		if err := tmux.UnsetHooks(h, "amx focus"); err != nil {
			return err
		}
	}
	for _, h := range hooks {
		target := "#{pane_id}"
		if h != "after-select-pane" {
			target = "#{session_name}:#{window_index}"
		}
		command := fmt.Sprintf(`run-shell -b "%s focus %s"`, exe, target)
		if err := tmux.SetHook(h, command); err != nil {
			return err
		}
	}
	fmt.Fprintln(opts.Out, "tmux hooks: installed")
	return nil
}

func mergeClaude(path, exe string, opts Options) error {
	var root map[string]json.RawMessage
	data, err := os.ReadFile(path)
	if err == nil {
		if err := json.Unmarshal(data, &root); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
	} else if errors.Is(err, os.ErrNotExist) {
		root = map[string]json.RawMessage{}
	} else {
		return err
	}
	if root == nil {
		root = map[string]json.RawMessage{}
	}

	hooks := map[string][]json.RawMessage{}
	if raw, ok := root["hooks"]; ok {
		if err := json.Unmarshal(raw, &hooks); err != nil {
			return fmt.Errorf("%s: hooks: %w", path, err)
		}
	}

	removed := 0
	for _, event := range claudeEvents {
		groups := hooks[event]
		kept := groups[:0]
		for _, g := range groups {
			if strings.Contains(string(g), "amux hook claude") {
				removed++
				continue
			}
			kept = append(kept, g)
		}
		hooks[event] = kept
	}

	added := 0
	for _, event := range claudeEvents {
		cmd := exe + " hook claude " + event
		found := false
		for _, group := range hooks[event] {
			if strings.Contains(string(group), cmd) {
				found = true
				break
			}
		}
		if found {
			continue
		}
		group := fmt.Sprintf(`{"hooks":[{"type":"command","command":%s,"timeout":5}]}`, jsonString(cmd))
		hooks[event] = append(hooks[event], json.RawMessage(group))
		added++
	}
	if added == 0 && removed == 0 {
		fmt.Fprintf(opts.Out, "claude hooks: unchanged (%s)\n", path)
		return nil
	}
	if opts.DryRun {
		fmt.Fprintf(opts.Out, "claude hooks: would add %d and remove %d handlers in %s\n", added, removed, path)
		return nil
	}

	rawHooks, err := json.Marshal(hooks)
	if err != nil {
		return err
	}
	root["hooks"] = rawHooks
	out, err := json.MarshalIndent(root, "", "  ")
	if err != nil {
		return err
	}
	out = append(out, '\n')

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if len(data) > 0 {
		backup := fmt.Sprintf("%s.amx-%s.bak", path, time.Now().Format("20060102-150405"))
		if err := os.WriteFile(backup, data, 0o644); err != nil {
			return err
		}
		fmt.Fprintf(opts.Out, "claude hooks: backup at %s\n", backup)
	}
	if err := os.WriteFile(path, out, 0o644); err != nil {
		return err
	}
	fmt.Fprintf(opts.Out, "claude hooks: added %d, removed %d handlers in %s\n", added, removed, path)
	return nil
}

func writePlugin(path, exe string, opts Options) error {
	const marker = "// amx: generated by amx setup. Do not edit."
	body := strings.ReplaceAll(pluginTemplate, "__AMX_BIN__", jsonString(exe))
	body = marker + "\n" + body

	if have, err := os.ReadFile(path); err == nil {
		if string(have) == body {
			fmt.Fprintf(opts.Out, "opencode plugin: unchanged (%s)\n", path)
			return nil
		}
		if !strings.HasPrefix(string(have), marker) {
			fmt.Fprintf(opts.Out, "opencode plugin: %s exists and was not generated by amx; leaving it alone\n", path)
			return nil
		}
	}
	if opts.DryRun {
		fmt.Fprintf(opts.Out, "opencode plugin: would write %s\n", path)
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(opts.Out, "opencode plugin: wrote %s\n", path)
	return nil
}

func jsonString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

const pluginTemplate = `// Reports OpenCode session state to amx (OpenCode v2 plugin API).
import { Plugin } from "@opencode/plugin"
import { spawn } from "node:child_process"

const BIN = __AMX_BIN__
const pane = process.env.TMUX_PANE
const launchDir = process.cwd()
let projectDir = undefined
let sessionID = undefined
let sessionTitle = undefined

function report(payload) {
  if (!pane && !projectDir) return
  try {
    const proc = spawn(BIN, ["report"], { detached: true, stdio: ["pipe", "ignore", "ignore"] })
    proc.on("error", () => {})
    proc.stdin.on("error", () => {})
    proc.stdin.end(JSON.stringify({ pane_id: pane, cwd: launchDir, project: projectDir, agent: "opencode", title: sessionTitle, ...payload }))
    proc.unref()
  } catch {}
}

function mine(event) {
  const id = event?.data?.sessionID || event?.properties?.sessionID
  return sessionID !== undefined && id !== undefined && id === sessionID
}

async function loadTitle(ctx) {
  if (!sessionID) return
  try {
    const info = await ctx.session.get({ sessionID })
    if (info?.title) sessionTitle = info.title
  } catch {}
}

async function handle(ctx, event) {
  if (!mine(event)) return
  switch (event.type) {
    case "session.execution.started":
      await loadTitle(ctx)
      report({ state: "running" })
      break
    case "session.execution.succeeded":
    case "session.execution.interrupted":
      await loadTitle(ctx)
      report({ state: "done_unseen" })
      break
    case "session.updated": {
      const title = event?.data?.title || event?.data?.session?.title || event?.data?.info?.title
      if (title) sessionTitle = title
      break
    }
    case "session.execution.failed":
      report({ state: "needs_input", detail: event?.data?.error?.type || "error" })
      break
    case "session.idle":
      report({ state: "done_unseen" })
      break
    case "session.status": {
      const status = event?.properties?.status?.type
      if (status === "busy") report({ state: "running" })
      else if (status === "idle") report({ state: "done_unseen" })
      break
    }
    case "permission.asked":
      report({ state: "needs_input", detail: "permission" })
      break
    case "permission.replied":
      report({ state: "running" })
      break
    case "session.error":
      report({ state: "needs_input", detail: "error" })
      break
    case "session.deleted":
      report({ state: "gone" })
      break
  }
}

export default Plugin.define({
  id: "amx",
  async setup(ctx) {
    projectDir = ctx.location?.directory || process.cwd()
    const controller = new AbortController()

    void (async () => {
      while (!controller.signal.aborted) {
        try {
          for await (const event of ctx.event.subscribe({ signal: controller.signal })) await handle(ctx, event)
        } catch {}
        if (!controller.signal.aborted) await new Promise((r) => setTimeout(r, 1000))
      }
    })()

    await ctx.session.hook("prompt", async (event) => {
      sessionID = event.sessionID
      await loadTitle(ctx)
      report({ state: "running" })
    })

    await ctx.tool.hook("execute.before", (event) => {
      report({ state: "running", detail: event.tool })
    })

    return () => controller.abort()
  },
})
`
